import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { resolveComponentRegistrySourcePaths } from "@drupal-canvas/headless/component-registry";
import { buildComponentMetadataPayload } from "@drupal-canvas/headless/components-endpoint";

const CONTENT_ENTITY_REFERENCE =
  "json-schema-definitions://canvas.module/content-entity-reference";
const IMAGE = "json-schema-definitions://canvas.module/image";
const VIDEO = "json-schema-definitions://canvas.module/video";
const TYPESCRIPT_PROPERTY_NAME = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

const imageSchema = {
  properties: {
    alt: { type: "string" },
    height: { type: "integer" },
    src: { type: "string" },
    width: { type: "integer" },
  },
  required: ["src"],
  type: "object",
};

const videoSchema = {
  properties: {
    poster: { type: "string" },
    src: { type: "string" },
  },
  required: ["src"],
  type: "object",
};

const projectRoot = fileURLToPath(new URL("..", import.meta.url));
const outputPath = resolve(projectRoot, "generated/canvas-component-props.ts");

export function generateCanvasComponentTypes(components, referenceSamples) {
  const sortedComponents = [...components].sort((left, right) =>
    left.machineName.localeCompare(right.machineName)
  );
  assertUniqueMachineNames(sortedComponents);

  const usesSlots = sortedComponents.some(
    (component) => Object.keys(component.slots).length > 0
  );
  const reactImports = usesSlots ? "ComponentType, ReactNode" : "ComponentType";
  const componentEntries = sortedComponents.map((component) =>
    renderComponentEntry(component, referenceSamples)
  );

  return `/**
 * Generated by \`pnpm canvas:typegen\` from Canvas component metadata.
 * Do not edit this file directly.
 *
 * Content entity reference shapes come from the first non-null value for the
 * prop in the component's Workbench mocks.json file. Use Canvas's
 * \`agents-context cer-preview\` command to inspect the resolved value when
 * creating or updating that mock.
 */
import type { ${reactImports} } from "react";

export type CanvasComponentPropsMap = {
${componentEntries.join("\n")}
};

export type CanvasComponentName = keyof CanvasComponentPropsMap;

export type CanvasComponentProps<
  Name extends CanvasComponentName,
> = CanvasComponentPropsMap[Name];

export type CanvasComponent<Name extends CanvasComponentName> = ComponentType<
  CanvasComponentProps<Name>
>;

export type CanvasComponentRegistry = {
  [Name in CanvasComponentName]: CanvasComponent<Name>;
};
`;
}

function renderComponentEntry(component, referenceSamples) {
  const required = new Set(component.required);
  const entries = [];
  const emittedNames = new Set();

  for (const [propName, schema] of Object.entries(component.props)) {
    const sample = referenceSamples.get(
      referenceSampleKey(component, propName)
    );
    entries.push({
      name: propName,
      optional: !required.has(propName),
      type: schemaToType(schema, sample, 2),
    });
    emittedNames.add(propName);
  }

  for (const slotName of Object.keys(component.slots)) {
    const propName = slotName === "default" ? "children" : slotName;
    if (emittedNames.has(propName)) {
      throw new Error(
        `Canvas component '${component.machineName}' defines both a prop and slot that render as '${propName}'.`
      );
    }
    entries.push({ name: propName, optional: true, type: "ReactNode" });
    emittedNames.add(propName);
  }

  return `  ${JSON.stringify(component.machineName)}: ${renderObjectType(
    entries,
    1
  )};`;
}

function schemaToType(schema, referenceSample, indentLevel) {
  if (Array.isArray(schema.enum) && schema.enum.length > 0) {
    return schema.enum.map(renderLiteral).join(" | ");
  }

  if (schema.$ref === CONTENT_ENTITY_REFERENCE) {
    if (referenceSample === undefined) {
      throw new Error(
        "A content entity reference needs a representative non-null value in Workbench mocks.json."
      );
    }
    return `${valueToType(referenceSample, indentLevel)} | null`;
  }

  if (schema.$ref === IMAGE) {
    return schemaToType(imageSchema, undefined, indentLevel);
  }

  if (schema.$ref === VIDEO) {
    return schemaToType(videoSchema, undefined, indentLevel);
  }

  if (Array.isArray(schema.type)) {
    const types = schema.type.map((type) =>
      schemaToType({ ...schema, type }, referenceSample, indentLevel)
    );
    return [...new Set(types)].join(" | ");
  }

  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      const itemType = schema.items
        ? schemaToType(schema.items, undefined, indentLevel)
        : "unknown";
      return `Array<${itemType}>`;
    }
    case "object": {
      const required = new Set(schema.required ?? []);
      const entries = Object.entries(schema.properties ?? {}).map(
        ([name, propertySchema]) => ({
          name,
          optional: !required.has(name),
          type: schemaToType(propertySchema, undefined, indentLevel + 1),
        })
      );
      return entries.length > 0
        ? renderObjectType(entries, indentLevel)
        : "Record<string, unknown>";
    }
    default:
      return "unknown";
  }
}

function valueToType(value, indentLevel) {
  if (value === null) {
    return "unknown";
  }

  if (Array.isArray(value)) {
    if (value.length === 0) {
      return "Array<unknown>";
    }
    const itemTypes = [
      ...new Set(value.map((item) => valueToType(item, indentLevel))),
    ];
    return `Array<${itemTypes.join(" | ")}>`;
  }

  switch (typeof value) {
    case "string":
      return "string";
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "object": {
      const entries = Object.entries(value).map(([name, child]) => ({
        name,
        optional: true,
        type: addNull(valueToType(child, indentLevel + 1)),
      }));
      return renderObjectType(entries, indentLevel);
    }
    default:
      return "unknown";
  }
}

function addNull(type) {
  return type === "null" || type.endsWith(" | null") ? type : `${type} | null`;
}

function renderObjectType(entries, indentLevel) {
  if (entries.length === 0) {
    return "Record<string, never>";
  }

  const propertyIndent = "  ".repeat(indentLevel + 1);
  const closingIndent = "  ".repeat(indentLevel);
  const properties = entries.map(
    ({ name, optional, type }) =>
      `${propertyIndent}${renderPropertyName(name)}${optional ? "?" : ""}: ${type};`
  );
  return `{\n${properties.join("\n")}\n${closingIndent}}`;
}

function renderPropertyName(name) {
  return TYPESCRIPT_PROPERTY_NAME.test(name) ? name : JSON.stringify(name);
}

function renderLiteral(value) {
  if (["string", "number", "boolean"].includes(typeof value)) {
    return JSON.stringify(value);
  }
  throw new Error(
    `Canvas enum values must be scalar. Received ${String(value)}.`
  );
}

function assertUniqueMachineNames(components) {
  const seen = new Set();
  for (const component of components) {
    if (seen.has(component.machineName)) {
      throw new Error(
        `Cannot generate Canvas prop types for duplicate machine name '${component.machineName}'.`
      );
    }
    seen.add(component.machineName);
  }
}

function referenceSampleKey(component, propName) {
  return `${component.machineName}:${propName}`;
}

async function loadReferenceSamples(components, componentRoot) {
  const entries = await Promise.all(
    components.map(async (component) => {
      const referenceProps = Object.entries(component.props)
        .filter(([, schema]) => schema.$ref === CONTENT_ENTITY_REFERENCE)
        .map(([propName]) => propName);
      if (referenceProps.length === 0) {
        return [];
      }

      const mocksPath = resolve(
        componentRoot,
        component.relativeDirectory,
        "mocks.json"
      );
      const mocks = await readMocks(mocksPath);

      return referenceProps.map((propName) => {
        const value = mocks
          .map((mock) => mock?.props?.[propName])
          .find((candidate) => candidate !== undefined && candidate !== null);
        if (value === undefined) {
          throw new Error(
            `Canvas component '${component.machineName}' needs a non-null '${propName}' value in ${mocksPath}. Run 'pnpm exec canvas agents-context cer-preview ${component.machineName}' to inspect the resolved shape.`
          );
        }
        return [referenceSampleKey(component, propName), value];
      });
    })
  );

  return new Map(entries.flat());
}

async function readMocks(mocksPath) {
  let source;
  try {
    source = await readFile(mocksPath, "utf8");
  } catch (error) {
    if (isFileNotFoundError(error)) {
      return [];
    }
    throw error;
  }

  const parsed = JSON.parse(source);
  return Array.isArray(parsed?.mocks) ? parsed.mocks : [];
}

function isFileNotFoundError(error) {
  return error instanceof Error && "code" in error && error.code === "ENOENT";
}

async function main() {
  const args = new Set(process.argv.slice(2));
  const unknownArgs = [...args].filter((arg) => arg !== "--check");
  if (unknownArgs.length > 0) {
    throw new Error(`Unknown option(s): ${unknownArgs.join(", ")}`);
  }

  const { componentRoot } = resolveComponentRegistrySourcePaths({
    projectRoot,
  });
  const payload = await buildComponentMetadataPayload({ projectRoot });
  const referenceSamples = await loadReferenceSamples(
    payload.components,
    componentRoot
  );
  const source = generateCanvasComponentTypes(
    payload.components,
    referenceSamples
  );

  for (const warning of payload.warnings) {
    process.stderr.write(`[canvas:typegen] ${warning.message}\n`);
  }

  if (args.has("--check")) {
    const current = await readFile(outputPath, "utf8").catch((error) => {
      if (isFileNotFoundError(error)) {
        return;
      }
      throw error;
    });
    if (current !== source) {
      throw new Error(
        "Canvas component prop types are stale. Run 'pnpm canvas:typegen'."
      );
    }
    process.stdout.write("Canvas component prop types are up to date.\n");
    return;
  }

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, source, "utf8");
  process.stdout.write(
    `Generated ${payload.components.length} Canvas component prop type(s) in ${outputPath}.\n`
  );
}

const entryPath = process.argv[1] ? resolve(process.argv[1]) : undefined;
if (entryPath === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    const message = error instanceof Error ? error.message : String(error);
    process.stderr.write(`${message}\n`);
    process.exitCode = 1;
  });
}
